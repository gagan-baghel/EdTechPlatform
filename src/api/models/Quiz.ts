import { Schema } from "mongoose"

import type {
  Quiz as QuizEntity,
  QuizQuestion as QuizQuestionEntity,
} from "@/types/domain"
import { defineModel, type ObjectId, type SchemaOf } from "../lib/mongoose"

/**
 * A quiz belongs to a course, optionally scoped to one lecture
 * (subSection). Course-level quizzes (subSection unset) act as a final
 * assessment; lecture-level ones check understanding of that specific
 * video. correctOptionIndex is never sent to students — see Quiz.js
 * controller's getQuizForStudent, which strips it before responding.
 */
const questionSchema = new Schema<SchemaOf<QuizQuestionEntity<ObjectId>>>(
  {
    questionText: { type: String, required: true },
    options: {
      type: [String],
      required: true,
      validate: (arr: string[]) => arr.length >= 2,
    },
    correctOptionIndex: { type: Number, required: true, min: 0 },
    explanation: { type: String },
  },
  { _id: true }
)

const quizSchema = new Schema<SchemaOf<QuizEntity<ObjectId>>>(
  {
    course: { type: Schema.Types.ObjectId, ref: "Course", required: true, index: true },
    subSection: { type: Schema.Types.ObjectId, ref: "SubSection", default: null },
    title: { type: String, required: true },
    questions: {
      type: [questionSchema],
      validate: (arr: unknown[]) => arr.length > 0,
    },
    passingScorePercent: { type: Number, default: 70, min: 0, max: 100 },
    createdBy: { type: Schema.Types.ObjectId, ref: "User", required: true },
    // Instructor drafts (possibly AI-generated by the copilot) start
    // unpublished — a quiz is never visible to students until an
    // instructor explicitly approves it. Same human-review gate the plan
    // requires for any AI-assisted content.
    published: { type: Boolean, default: false },
  },
  { timestamps: true }
)
export const Quiz = defineModel("Quiz", quizSchema)
export default Quiz